import Foundation

let a = RemoteComposerDraftScope(hostID: "host-a", threadID: "same")
let b = RemoteComposerDraftScope(hostID: "host-b", threadID: "same")
let session = UUID()
let snapshot = RemoteAgentsSnapshot.fixture(scope: a)
precondition(snapshot.hasValidIdentity && snapshot.count == 3)
let intent = snapshot.openIntent(agentID: "fixture-agent-layout", sessionID: session)!
precondition(snapshot.resolve(intent, currentSession: session)?.status == .running)
precondition(snapshot.resolve(intent, currentSession: UUID()) == nil)
precondition(RemoteAgentsSnapshot.fixture(scope: b).resolve(intent, currentSession: session) == nil)
let revised = RemoteAgentsSnapshot(scope: a, revision: 2, sections: snapshot.sections)
precondition(revised.resolve(intent, currentSession: session) == nil)
let rosterRequest = RemoteAgentRosterRequest(accountID: "account", profileID: "profile", scope: a, sessionID: session)
let receipt = RemoteAgentRosterReceipt(request: rosterRequest, snapshot: revised)
let retry = RemoteAgentRosterRequest(accountID: "account", profileID: "profile", scope: a, sessionID: session)
precondition(receipt.resolve(for: retry, previous: snapshot) == .invalid)
precondition(receipt.resolve(for: rosterRequest, previous: snapshot) == .accepted(revised))
precondition(receipt.resolve(for: rosterRequest, previous: revised) == .accepted(revised))
precondition(receipt.resolve(for: .init(accountID: "other", profileID: "profile", scope: a, sessionID: session), previous: nil) == .invalid)
precondition(receipt.resolve(for: .init(accountID: "account", profileID: "other", scope: a, sessionID: session), previous: nil) == .invalid)
precondition(receipt.resolve(for: .init(accountID: "account", profileID: "profile", scope: a, sessionID: UUID()), previous: nil) == .invalid)
precondition(RemoteAgentRosterReceipt(request: rosterRequest, snapshot: snapshot).resolve(for: rosterRequest, previous: revised) == .stale)
precondition(RemoteAgentRosterReceipt(request: rosterRequest, snapshot: .fixture(scope: b)).resolve(for: rosterRequest, previous: nil) == .invalid)
let cleared = RemoteAgentsSnapshot(scope: a, revision: 3, sections: [])
precondition(RemoteAgentRosterReceipt(request: rosterRequest, snapshot: cleared).resolve(for: rosterRequest, previous: revised) == .accepted(cleared))
let conflict = RemoteAgentRosterReceipt(request: rosterRequest, snapshot: .init(scope: a, revision: 2, sections: []))
precondition(conflict.resolve(for: rosterRequest, previous: revised) == .invalid)
let target = RemoteAgentThreadTarget(hostID: "host-a", threadID: "resolved-child", title: "Child")
let threadRequest = RemoteAgentThreadRequest(accountID: "account", profileID: "profile", intent: intent, snapshot: snapshot, sessionID: session)!
precondition(threadRequest.resolve(target, accountID: "account", profileID: "profile", snapshot: snapshot, sessionID: session, availableHosts: ["host-a"]) == target)
precondition(threadRequest.resolve(target, accountID: "account", profileID: "other", snapshot: snapshot, sessionID: session, availableHosts: ["host-a"]) == nil)
precondition(snapshot.openIntent(agentID: "missing", sessionID: session) == nil)
var duplicate = snapshot
let first = duplicate.sections[0].subagents[0]
var readOnlySnapshot = snapshot
readOnlySnapshot.sections[0].subagents[0].canOpenAssociatedTask = false
precondition(readOnlySnapshot.openIntent(agentID: first.id, sessionID: session) == nil)
precondition(readOnlySnapshot.resolve(intent, currentSession: session) == nil)
precondition(threadRequest.resolve(target, accountID: "account", profileID: "profile", snapshot: readOnlySnapshot, sessionID: session, availableHosts: ["host-a"]) == nil)
duplicate.sections[1].subagents.append(first)
precondition(!duplicate.hasValidIdentity)
precondition(duplicate.openIntent(agentID: first.id, sessionID: session) == nil)
precondition(duplicate.resolve(intent, currentSession: session) == nil)
var duplicateSection = snapshot
duplicateSection.sections.append(.init(id: .active, subagents: []))
precondition(!duplicateSection.hasValidIdentity)
let empty = RemoteAgentsSnapshot(scope: a, revision: 0, sections: [])
precondition(empty.hasValidIdentity && empty.count == 0)
precondition(empty.openIntent(agentID: first.id, sessionID: session) == nil)
let invalid = RemoteAgentsSnapshot(scope: a, revision: -1, sections: [])
precondition(!invalid.hasValidIdentity)
precondition(RemoteAgentStatus.allCases.count == 10)
print("Remote agents: exact host/task/session/revision, missing targets, duplicate identities, empty state and status cases passed")
