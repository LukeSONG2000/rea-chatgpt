import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createFixtureHost} from './desktop-fixture-services.mjs';
globalThis.location={origin:'https://offline.invalid'};
const historyFixture=JSON.parse(fs.readFileSync(new URL('../desktop-official-20261104/history-fixture-replay.json',import.meta.url))).converted_fixture;
const {host}=createFixtureHost({Wst:class {}},{scenario:'synthetic-account',historyFixture});
const service=host.services.httpFetch;
let userIndex=0;
const request=conversation=>({method:'POST',url:'/f/conversation',body:JSON.stringify({conversation_id:conversation,parent_message_id:conversation.endsWith('002')?'offline-assistant-002':'offline-assistant-001',messages:[{id:'synthetic-user-'+(++userIndex)}]})});
const {response}=await service.fetch('first',request('offline-fixture-conversation-001'));
const body=await response.text();
const objects=body.split('\n\n').filter(x=>x.startsWith('data: {')).map(x=>JSON.parse(x.slice(6)));
assert.equal(objects.length,4);
assert.deepEqual(objects.slice(0,3).map(x=>x.message.status),['in_progress','in_progress','finished_successfully']);
assert.equal(new Set(objects.slice(0,3).map(x=>x.message.id)).size,1);
assert.equal(objects[0].message.metadata.parent_id,'synthetic-user-1');
assert.equal(objects[3].type,'message_stream_complete');
assert.ok(body.endsWith('data: [DONE]\n\n'));
const a=await service.fetch('a',request('offline-fixture-conversation-001'));
const b=await service.fetch('b',request('offline-fixture-conversation-002'));
service.cancel('a');
assert.equal(await a.response.text(),'');
assert.ok((await b.response.text()).includes('message_stream_complete'));
const c=await service.fetch('stop-a',request('offline-fixture-conversation-001'));
const d=await service.fetch('keep-b',request('offline-fixture-conversation-002'));
await service.fetch('stop-command',{method:'POST',url:'/stop_conversation',body:JSON.stringify({conversation_id:'offline-fixture-conversation-001',exclude_async_types:[]})});
assert.equal(await c.response.text(),'');
assert.ok((await d.response.text()).includes('message_stream_complete'));
const restored=await service.fetch('history',{method:'GET',url:'/conversation/offline-fixture-conversation-001'});
const snapshot=await restored.response.json();
assert.equal(snapshot.mapping[snapshot.current_node].message.status,'finished_partial_completion');
await assert.rejects(()=>service.fetch('invalid',request('other-conversation')),/Unknown synthetic conversation/);
console.log('passed: incremental snapshots, stable identity, completion, stream/conversation cancellation isolation, in-memory history, conversation allowlist');
