import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createFixtureHost} from './desktop-fixture-services.mjs';
globalThis.location={origin:'https://offline.invalid'};
const fixture=JSON.parse(fs.readFileSync(new URL('../desktop-official-20261104/history-fixture-replay.json',import.meta.url))).converted_fixture;
const {host}=createFixtureHost({Wst:class{}},{scenario:'synthetic-account',historyFixture:fixture});
const http=host.services.httpFetch;
const get=async id=>(await http.fetch('read-'+id,{method:'GET',url:'/conversation/'+id})).response.json();
const bBefore=await get('offline-fixture-conversation-002');
const user={...structuredClone(fixture.mapping['offline-user-001'].message),id:'synthetic-edit-user',content:{content_type:'text',parts:['REA synthetic edited message branch']}};
const body={conversation_id:fixture.conversation_id,parent_message_id:fixture.mapping['offline-user-001'].parent,messages:[user],action:'next'};
const stream=await http.fetch('edit',{method:'POST',url:'/f/conversation',body:JSON.stringify(body)});
await stream.response.text();
const a=await get(fixture.conversation_id);
assert.deepEqual(a.mapping['offline-user-001'],fixture.mapping['offline-user-001']);
assert.deepEqual(a.mapping['offline-assistant-001'],fixture.mapping['offline-assistant-001']);
assert.ok(a.mapping[body.parent_message_id].children.includes(user.id));
assert.ok(a.mapping[body.parent_message_id].children.includes('offline-user-001'));
assert.equal(a.mapping[a.current_node].parent,user.id);
assert.equal(a.mapping[a.current_node].message.status,'finished_successfully');
assert.deepEqual(await get('offline-fixture-conversation-002'),bBefore);
await assert.rejects(http.fetch('duplicate',{method:'POST',url:'/f/conversation',body:JSON.stringify(body)}),/Unknown synthetic parent\/message/);
assert.deepEqual(await get(fixture.conversation_id),a);
console.log('passed: edit sibling branch, original nodes retained, completed leaf, other conversation isolation, duplicate rejection without mutation');
