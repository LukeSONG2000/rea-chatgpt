win.isFocused=()=>focused;win.isDestroyed=()=>destroyed;win.webContents={getURL:()=>url};
const messages=[],audit=[];
const bridge=bindWindowFocus(win,m=>messages.push(m),m=>audit.push(m),()=>1234);
win.emit('focus');assert.equal(messages.length,0);
url='https://offline.invalid.evil/';win.emit('blur');assert.equal(messages.length,0);
